#!/usr/bin/env python3
"""Montserrat static TTFs ko subset + family-name normalize karke
app/fonts_data.h banata hai. DirectWrite family "Montserrat" ke andar
weights 400/600/700/800/900 saaf group hon — isi liye name IDs theek
kiye jate hain. Chalana: PYTHONPATH=<fonttools> python3 tools/setup-assets.py
Source TTFs: /tmp/Montserrat-master/fonts/ttf (JulietaUla/Montserrat)."""
import io
import os
import sys

sys.path.insert(0, "/tmp/pypkg")
from fontTools import subset
from fontTools.ttLib import TTFont

HERE = os.path.dirname(os.path.abspath(__file__))
APP = os.path.dirname(HERE)
SRC_DIR = "/tmp/Montserrat-master/fonts/ttf"

WEIGHTS = [  # (file suffix, subfamily name, OS/2 weight)
    ("Regular", "Regular", 400),
    ("SemiBold", "SemiBold", 600),
    ("Bold", "Bold", 700),
    ("ExtraBold", "ExtraBold", 800),
    ("Black", "Black", 900),
]

UNICODES = (
    list(range(0x20, 0x7F)) + list(range(0xA0, 0x100))
    + [0x2013, 0x2014, 0x2018, 0x2019, 0x201A, 0x201C, 0x201D, 0x201E,
       0x2020, 0x2021, 0x2022, 0x2026, 0x2030, 0x2039, 0x203A,
       0x20B9, 0x2190, 0x2192, 0x2713]
)


def set_name(font, nid, text):
    for plat in ((3, 1, 0x409), (1, 0, 0)):
        font["name"].setName(text, nid, *plat)


def main():
    blobs = []
    for suffix, subfamily, weight in WEIGHTS:
        path = os.path.join(SRC_DIR, f"Montserrat-{suffix}.ttf")
        font = TTFont(path)
        # family normalize: sab "Montserrat", farq sirf subfamily/weight
        for nid, text in ((1, "Montserrat"), (16, "Montserrat"),
                          (2, subfamily), (17, subfamily),
                          (4, f"Montserrat {subfamily}"),
                          (6, f"Montserrat-{subfamily}")):
            set_name(font, nid, text)
        font["OS/2"].usWeightClass = weight
        font["head"].macStyle = 1 if weight >= 700 else 0
        opts = subset.Options(notdef_outline=True, layout_features=["kern", "liga"])
        subsetter = subset.Subsetter(options=opts)
        subsetter.populate(unicodes=UNICODES)
        subsetter.subset(font)
        buf = io.BytesIO()
        font.save(buf)
        data = buf.getvalue()
        blobs.append((suffix, data))
        print(f"{suffix}: {len(data)//1024} KB, weight {weight}")

    out = ["/* GENERATED by tools/setup-assets.py — embedded Montserrat (OFL 1.1) */",
           "#pragma once", "",
           "struct EmbeddedFont { const unsigned char* data; unsigned int size; };", ""]
    for i, (suffix, data) in enumerate(blobs):
        out.append(f"static const unsigned char g_font_{suffix}[] = {{")
        for off in range(0, len(data), 20):
            out.append("    " + ",".join(str(b) for b in data[off:off + 20]) + ",")
        out.append("};")
        out.append("")
    out.append("static const EmbeddedFont g_embeddedFonts[] = {")
    for suffix, data in blobs:
        out.append(f"    {{ g_font_{suffix}, {len(data)} }},")
    out.append("};")
    out.append("")
    with open(os.path.join(APP, "fonts_data.h"), "w") as f:
        f.write("\n".join(out))
    print("fonts_data.h:", os.path.getsize(os.path.join(APP, "fonts_data.h")) // 1024, "KB")


if __name__ == "__main__":
    main()
